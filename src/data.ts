function buildCountry(row: Row): Country {
  const [
    name, flag, region, capital, population, area,
    government, currency, language, gdp, gdpPerCapita, birthRate, lifeExp,
  ] = row;

  const field = (label: string, value: string) => ({
    id: uid('field'),
    label,
    value,
  });

  return {
    id: uid('country'),
    name,
    flag,
    region,
    categories: [
      {
        id: uid('cat'),
        name: '기본',
        fields: [
          field('수도', capital),
          field('인구', `${population}명`),
          field('면적', `${area} km²`),
          field('정부형태', government),
          field('통화', currency),
          field('공용어', language),
        ],
      },
      {
        id: uid('cat'),
        name: '경제',
        fields: [
          field('GDP (명목)', gdp),
          field('1인당 GDP', gdpPerCapita),
        ],
      },
      {
        id: uid('cat'),
        name: '사회',
        fields: [
          field('합계출산율', birthRate),
          field('기대수명', lifeExp === '-' ? '-' : `${lifeExp}세`),
        ],
      },
    ],
  };
}

export function seedWorld(): WorldState {
  return {
    asOf: '2026-06-01',
    countries: ROWS.map(buildCountry),
  };
}
