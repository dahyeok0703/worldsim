function buildCountry(raw: RawCountry): Country {
  return {
    id: uid('country'),
    name: raw.name,
    flag: raw.flag,
    categories: Object.entries(raw.categories).map(([catName, fields]) => ({
      id: uid('cat'),
      name: catName,
      fields: Object.entries(fields).map(([label, value]) => ({
        id: uid('field'),
        label,
        value,
      })),
    })),
  };
}

export function seedWorld(): WorldState {
  return {
    asOf: '2026-06-01',
    countries: RAW.map(buildCountry),
  };
}
